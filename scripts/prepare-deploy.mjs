// Build a deployable copy of web/ in dist/.
//
// The browser player normally reads its ROM/BIOS from web/games/, which is
// git-ignored. On the live site those files come from a public R2 bucket, so
// this script copies the site, drops games/, and rewrites deploy-config.js with
// the production URLs and flags. Nothing about local development changes.
//
// Usage:
//   R2_PUBLIC_BASE=https://pub-xxxx.r2.dev node scripts/prepare-deploy.mjs
//
// R2_PUBLIC_BASE is the only required input. It can also be written into
// scripts/deploy.env (git-ignored) for convenience.

import { cp, rm, mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "web");
const dest = join(root, "dist");

async function readEnvFile(path) {
  try {
    const text = await readFile(path, "utf8");
    const out = {};
    for (const line of text.split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.+?)\s*$/i);
      if (m) out[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
    }
    return out;
  } catch {
    return {};
  }
}

const fileEnv = await readEnvFile(join(root, "scripts", "deploy.env"));
const env = { ...fileEnv, ...process.env };
const base = (env.R2_PUBLIC_BASE ?? "").replace(/\/+$/, "");

if (!base) {
  console.error(
    "R2_PUBLIC_BASE is required (e.g. https://pub-xxxx.r2.dev).\n" +
      "Set it in the environment or in scripts/deploy.env (git-ignored).",
  );
  process.exit(1);
}

await rm(dest, { recursive: true, force: true });
await mkdir(dest, { recursive: true });
await cp(src, dest, {
  recursive: true,
  filter: (source) =>
    !["games", "tests"].some((part) => source.split(/[\\/]/).includes(part)),
});

const config = `// Generated by scripts/prepare-deploy.mjs — do not edit by hand.\nglobalThis.TONY_HANDS_ASSETS = ${JSON.stringify(
  {
    rom: `${base}/thps.bin`,
    bios: `${base}/scph5501.bin`,
    autoStart: true,
    defaultMode: "keyboard",
  },
  null,
  2,
)};\n`;
await writeFile(join(dest, "deploy-config.js"), config, "utf8");

console.log(`Prepared dist/ with assets from ${base}`);
console.log("Games folder excluded; next steps: upload assets, then wrangler pages deploy dist");
